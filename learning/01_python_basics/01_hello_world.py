# The print() function displays text on the screen.
# Text wrapped in quotes "like this" is called a STRING (a piece of text).
print("Hello, World!")

# You can print as many times as you like. Each print starts a new line.
print("My name is... (put your name here!)")
print("I am learning to code.")

# You can print numbers too (no quotes needed for numbers).
print(7)
print(3 + 4)  # Python does the math first, then prints the result: 7

# You can combine text and put blank lines for readability.
print()  # an empty print() just prints a blank line
print("Notice the blank line above this one.")


